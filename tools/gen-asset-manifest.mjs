/* ============================================================================
   gen-asset-manifest.mjs  —  writes asset-manifest.js
   ----------------------------------------------------------------------------
   The preloader needs to draw a byte-accurate bar BEFORE it has fetched
   anything, which means it needs every file's real size up front. Guessing is
   what makes loading bars jump around, so this reads the actual bytes off disk
   and emits a { url: bytes } table.

   It also collects the EMBEDDED GAME's assets. That part matters more than it
   looks: the game paints its sprites as CSS background-image on nodes that
   start display:none, and a hidden node's background-image is never fetched —
   so without warming these by hand the game hits the network mid-play. The
   paths come out of game/js/data.js (the same tree the game itself walks), so
   the list cannot drift from what the game actually asks for.

   ⚠ EXACT URLs. The warm only works if the string here is byte-identical to
   what the browser will request — same casing, same encoding, and the same
   query string. Nothing in this project appends a ?v= cache-buster today; if
   one is ever added, add it HERE too (see BUST below) or every warmed entry
   will miss and the loading bar will lie.

   Run:  node tools/gen-asset-manifest.mjs
   ============================================================================ */
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');

// If the project ever cache-busts its assets, set this to the same suffix the
// runtime appends (e.g. `?v=${BUILD}`) so the warmed URLs match exactly.
const BUST = '';

const bytes = (p) => { try { return fs.statSync(p).size; } catch { return 0; } };
const post = (u) => u + BUST;

const manifest = {};
const add = (rel) => {
  const abs = path.join(ROOT, rel);
  const n = bytes(abs);
  if (!n) { console.warn('  ! missing, skipped:', rel); return; }
  // URL-encode each path segment (filenames here contain spaces)
  const u = rel.split('/').map(encodeURIComponent).join('/');
  manifest[post(u)] = n;
};

// ── 1. the shell's own media ────────────────────────────────────────────────
console.log('shell media:');
for (const dir of ['assets', 'assets/posters', 'sfx']) {
  for (const f of fs.readdirSync(path.join(ROOT, dir))) {
    const rel = `${dir}/${f}`;
    if (fs.statSync(path.join(ROOT, rel)).isFile()) add(rel);
  }
}

// ── 2. the embedded game ────────────────────────────────────────────────────
// its document, code and stylesheet…
console.log('game shell:');
const gameHtml = fs.readFileSync(path.join(ROOT, 'game/index.html'), 'utf8');
add('game/index.html');
for (const m of gameHtml.matchAll(/(?:src|href)="([^"]+)"/g)) {
  if (/^(https?:)?\/\//.test(m[1])) continue;       // webfonts / CDNs stay external
  add(`game/${m[1]}`);
}

// …and every sprite / clip / font its data tree references. Same discovery the
// game's own embed-bridge does, so the two lists cannot disagree.
console.log('game assets:');
const data = fs.readFileSync(path.join(ROOT, 'game/js/data.js'), 'utf8');
const found = new Set();
for (const m of data.matchAll(/"(assets\/[^"]+\.(?:webp|png|jpe?g|gif|svg|ogg|mp3|wav|m4a|ttf|woff2?))"/g)) {
  found.add(m[1]);
}
// referenced only from css/style.css url(...) — invisible to a data-tree walk
const gameCss = fs.readFileSync(path.join(ROOT, 'game/css/style.css'), 'utf8');
for (const m of gameCss.matchAll(/url\(['"]?\.\.\/([^'")]+)['"]?\)/g)) found.add(m[1]);

for (const rel of [...found].sort()) add(`game/${rel}`);

// ── write ───────────────────────────────────────────────────────────────────
const entries = Object.entries(manifest).sort((a, b) => a[1] - b[1]);   // smallest first
const total = entries.reduce((s, [, n]) => s + n, 0);
const out =
`/* AUTO-GENERATED by tools/gen-asset-manifest.mjs — do not edit by hand.
   Real on-disk byte sizes for every file the preloader warms, so the loading bar
   is accurate from the very first frame instead of guessing and jumping.
   Keys are the EXACT request URLs (encoded per segment). Regenerate whenever
   media is added, removed or re-encoded:  node tools/gen-asset-manifest.mjs
   ${entries.length} files, ${(total / 1e6).toFixed(2)} MB total. */
window.ASSET_MANIFEST = {
${entries.map(([u, n]) => `  ${JSON.stringify(u)}: ${n}`).join(',\n')}
};
`;
fs.writeFileSync(path.join(ROOT, 'asset-manifest.js'), out);
console.log(`\nasset-manifest.js: ${entries.length} files, ${(total / 1e6).toFixed(2)} MB`);
